test("stacks, unstacks, encodes, and clips eager tensors", function()
  local context = tf.eager.Context.new()
  local a = context:constant({ 1, 2 })
  local b = context:constant({ 3, 4 })
  local rows = context:stack({ a, b }, 0)
  local columns = context:stack({ a, b }, 1)
  assert_eq(table.concat(rows:shape(), ","), "2,2")
  assert_eq(rows:totable()[1][1], 1)
  assert_eq(rows:totable()[2][2], 4)
  assert_eq(table.concat(columns:shape(), ","), "2,2")
  assert_eq(columns:totable()[1][2], 3)
  assert_eq(columns:totable()[2][1], 2)

  local row_parts = context:unstack(rows, 2, 0)
  local column_parts = context:unstack(columns, 2, 1)
  assert_eq(#row_parts, 2)
  assert_eq(#column_parts, 2)
  assert_eq(row_parts[1]:totable()[2], 2)
  assert_eq(row_parts[2]:totable()[1], 3)
  assert_eq(column_parts[1]:totable()[1], 1)
  assert_eq(column_parts[2]:totable()[2], 4)

  local encoded = context:one_hot(context:constant({ 0, 2 }, "int32"), 3,
    { dtype = "int32", on_value = 1, off_value = 0 })
  assert_eq(encoded:dtype(), "int32")
  assert_eq(table.concat(encoded:shape(), ","), "2,3")
  assert_eq(encoded:totable()[1][1], 1)
  assert_eq(encoded:totable()[1][2], 0)
  assert_eq(encoded:totable()[2][3], 1)

  local clipped = context:clip_by_value(context:constant({ -2, 0, 3 }), -1, 1)
  assert_eq(clipped:totable()[1], -1)
  assert_eq(clipped:totable()[2], 0)
  assert_eq(clipped:totable()[3], 1)

  assert_error(function() context:stack({}, 0) end, "non-empty")
  assert_error(function() context:stack({ a }, 0.5) end, "axis")
  assert_error(function() context:unstack(rows, 0, 0) end, "positive")
  assert_error(function() context:unstack(rows, 2, 0.5) end, "axis")
  assert_error(function() context:one_hot(a, 0) end, "positive")
  assert_error(function() context:clip_by_value(a, "-1", 1) end, "numeric")
  context:close()
end)

test("compares and combines eager tensors", function()
  local context = tf.eager.Context.new()
  local x = context:constant({ 1, 2, 3 }, "int32")
  local y = context:constant({ 2, 2, 2 }, "int32")
  local equal = context:equal(x, y)
  local not_equal = context:not_equal(x, y)
  local greater = context:greater(x, y)
  local greater_equal = context:greater_equal(x, y)
  local less = context:less(x, y)
  local less_equal = context:less_equal(x, y)
  assert_eq(equal:dtype(), "bool")
  assert_eq(equal:totable()[1], false)
  assert_eq(equal:totable()[2], true)
  assert_eq(not_equal:totable()[1], true)
  assert_eq(not_equal:totable()[3], true)
  assert_eq(greater:totable()[3], true)
  assert_eq(greater_equal:totable()[2], true)
  assert_eq(less:totable()[1], true)
  assert_eq(less_equal:totable()[3], false)

  local a = context:constant({ true, true, false })
  local b = context:constant({ true, false, false })
  local conjunction = context:logical_and(a, b)
  local disjunction = context:logical_or(a, b)
  local exclusive = context:logical_xor(a, b)
  local negation = context:logical_not(a)
  assert_eq(conjunction:totable()[1], true)
  assert_eq(conjunction:totable()[2], false)
  assert_eq(disjunction:totable()[2], true)
  assert_eq(exclusive:totable()[1], false)
  assert_eq(exclusive:totable()[2], true)
  assert_eq(negation:totable()[1], false)
  assert_eq(negation:totable()[3], true)

  local flags = context:constant({
    { true, true, false },
    { true, true, true },
  })
  local all_rows = context:reduce_all(flags, { 1 })
  local any_rows = context:reduce_any(flags, { 1 })
  local all_values = context:reduce_all(flags, { 0, 1 })
  assert_eq(all_rows:dtype(), "bool")
  assert_eq(all_rows:totable()[1], false)
  assert_eq(all_rows:totable()[2], true)
  assert_eq(any_rows:totable()[1], true)
  assert_eq(any_rows:totable()[2], true)
  assert_eq(all_values:totable(), false)

  local maximum = context:maximum(context:constant({ 1, 5, 3 }),
    context:constant({ 4, 2, 3 }))
  local minimum = context:minimum(context:constant({ 1, 5, 3 }),
    context:constant({ 4, 2, 3 }))
  assert_eq(table.concat(maximum:totable(), ","), "4,5,3")
  assert_eq(table.concat(minimum:totable(), ","), "1,2,3")
  assert_error(function() context:reduce_all(flags, 0) end, "axes")
  context:close()
end)
