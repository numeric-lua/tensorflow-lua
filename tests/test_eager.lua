local tf = require("tensorflow")

test("executes eager constants and arithmetic", function()
  local context = tf.eager.Context.new()
  local a = context:constant({ { 1, 2 }, { 3, 4 } })
  local b = context:constant({ { 10, 20 }, { 30, 40 } })
  local sum = context:add(a, b)
  assert_eq(table.concat(sum:shape(), ","), "2,2")
  local values = sum:totable()
  assert_eq(values[1][1], 11)
  assert_eq(values[2][2], 44)
  local product = context:matmul(a, b)
  assert_eq(product:totable()[1][1], 70)
  local relu = context:relu(context:sub(a, b))
  assert_eq(relu:totable()[1][1], 0)
  context:close()
end)

test("rejects eager use after close", function()
  local context = tf.eager.Context.new()
  context:close()
  assert_error(function() context:constant({ 1 }) end, "closed")
end)
