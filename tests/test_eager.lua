local tf = require("tensorflow")

test("executes eager constants and arithmetic", function()
  local context = tf.eager.Context.new()
  local a = context:constant({ { 1, 2 }, { 3, 4 } })
  local b = context:constant({ { 10, 20 }, { 30, 40 } })
  local sum = context:add(a, b)
  assert_eq(table.concat(sum:shape(), ","), "2,2")
  local values = sum:totable()
  assert_eq(values[1][1], 11)
  assert_eq(values[2][2], 44)
  local product = context:matmul(a, b)
  assert_eq(product:totable()[1][1], 70)
  local relu = context:relu(context:sub(a, b))
  assert_eq(relu:totable()[1][1], 0)
  context:close()
end)

test("rejects eager use after close", function()
  local context = tf.eager.Context.new()
  context:close()
  assert_error(function() context:constant({ 1 }) end, "closed")
end)

test("reshapes eager tensors", function()
  local context = tf.eager.Context.new()
  local value = context:constant({ { 1, 2 }, { 3, 4 } })
  local reshaped = context:reshape(value, { 4 })
  assert_eq(table.concat(reshaped:shape(), ","), "4")
  assert_eq(reshaped:totable()[4], 4)
  context:close()
end)

test("divides and casts eager tensors", function()
  local context = tf.eager.Context.new()
  local quotient = context:div(context:constant({ 8, 9 }),
    context:constant({ 2, 3 }))
  assert_eq(table.concat(quotient:shape(), ","), "2")
  assert_eq(quotient:totable()[1], 4)
  assert_eq(quotient:totable()[2], 3)
  local cast = context:cast(context:constant({ 1.9, -2.2 }), "int32")
  assert_eq(cast:dtype(), "int32")
  assert_eq(cast:totable()[1], 1)
  assert_eq(cast:totable()[2], -2)
  context:close()
end)

test("transposes, expands, and squeezes eager tensors", function()
  local context = tf.eager.Context.new()
  local value = context:constant({ { 1, 2, 3 }, { 4, 5, 6 } })
  local transposed = context:transpose(value, { 1, 0 })
  assert_eq(table.concat(transposed:shape(), ","), "3,2")
  assert_eq(transposed:totable()[1][2], 4)
  local expanded = context:expand_dims(value, 0)
  assert_eq(table.concat(expanded:shape(), ","), "1,2,3")
  local squeezed = context:squeeze(expanded, 0)
  assert_eq(table.concat(squeezed:shape(), ","), "2,3")
  assert_eq(squeezed:totable()[2][3], 6)
  context:close()
end)

test("reduces and takes eager argmax", function()
  local context = tf.eager.Context.new()
  local value = context:constant({ { 1, 2, 3 }, { 6, 5, 4 } })
  local sum = context:reduce_sum(value, { 0 })
  assert_eq(table.concat(sum:shape(), ","), "3")
  assert_eq(sum:totable()[2], 7)
  local kept = context:reduce_sum(value, { 1 }, true)
  assert_eq(table.concat(kept:shape(), ","), "2,1")
  assert_eq(kept:totable()[2][1], 15)
  local indices = context:argmax(value, 1, "int32")
  assert_eq(indices:dtype(), "int32")
  assert_eq(indices:totable()[1], 2)
  assert_eq(indices:totable()[2], 0)
  context:close()
end)

test("handles eager strings and scalars", function()
  local context = tf.eager.Context.new()
  local text = context:constant({ "a", "b" })
  assert_eq(text:dtype(), "string")
  assert_eq(text:totable()[2], "b")
  local scalar = context:constant(3.5)
  assert_eq(#scalar:shape(), 0)
  assert_eq(scalar:totable(), 3.5)
  context:close()
end)

test("releases many eager handles", function()
  local context = tf.eager.Context.new()
  for i = 1, 50 do
    local value = context:constant({ i, i + 1 })
    assert_eq(value:totable()[1], i)
  end
  for _ = 1, 3 do collectgarbage("collect") end
  context:close()
end)

test("destroys eager tensors explicitly and rejects reuse", function()
  local capi = require("tensorflow.capi")
  local before = capi.released.eager_tensors
  local context = tf.eager.Context.new()
  local value = context:constant({ 3, 4 })
  value:destroy()
  value:destroy()
  assert_error(function() value:totable() end, "released")
  context:close()
  assert_true(capi.released.eager_tensors >= before + 1)
end)

test("defers context deletion until live eager tensors are released", function()
  local context = tf.eager.Context.new()
  local value = context:constant({ 7, 8 })
  context:close()
  assert_true(not context._state.deleted)
  assert_eq(value:totable()[2], 8)
  value:destroy()
  assert_true(context._state.deleted)
end)

test("finalizes unclosed eager contexts and handles", function()
  local capi = require("tensorflow.capi")
  local before_contexts = capi.released.contexts
  local before_tensors = capi.released.eager_tensors
  do
    local context = tf.eager.Context.new()
    for i = 1, 10 do
      local value = context:constant({ i })
      assert_eq(value:totable()[1], i)
    end
  end
  for _ = 1, 5 do collectgarbage("collect") end
  assert_true(capi.released.contexts >= before_contexts + 1)
  assert_true(capi.released.eager_tensors >= before_tensors + 10)
end)
