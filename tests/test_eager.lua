test("takes eager argmin, relu6, add_n, and log-sum-exp", function()
  local context = tf.eager.Context.new()
  local value = context:constant({ { 0, 1 }, { 1000, 1000 } })
  local minimum = context:argmin(context:constant({ 3, 1, 2 }), 0, "int32")
  assert_eq(minimum:dtype(), "int32")
  assert_eq(minimum:totable(), 1)
  local clipped = context:relu6(context:constant({ -1, 2, 9 }))
  assert_eq(table.concat(clipped:totable(), ","), "0,2,6")
  local summed = context:add_n({ context:constant({ 1, 2 }),
    context:constant({ 3, 4 }) })
  assert_eq(table.concat(summed:totable(), ","), "4,6")
  local lse = context:reduce_logsumexp(value, { 1 })
  assert_eq(table.concat(lse:shape(), ","), "2")
  assert_true(math.abs(lse:totable()[1] - math.log(1 + math.exp(1))) < 1e-5)
  assert_true(math.abs(lse:totable()[2] - (1000 + math.log(2))) < 1e-4)
  local kept = context:reduce_logsumexp(value, { 1 }, true)
  assert_eq(table.concat(kept:shape(), ","), "2,1")
  assert_error(function() context:add_n({}) end, "non-empty")
  assert_error(function() context:reduce_logsumexp(value, 1) end, "axes")
  assert_error(function() context:argmin(value, 0.5) end, "integer axis")
  context:close()
end)

test("executes eager batch matmul, fill, range, and linspace", function()
  local context = tf.eager.Context.new()
  local a = context:constant({ { { 1, 2, 3 }, { 4, 5, 6 } },
    { { 1, 0, 0 }, { 0, 1, 0 } } })
  local b = context:constant({ { { 1, 0 }, { 0, 1 }, { 1, 1 } },
    { { 1, 2 }, { 3, 4 }, { 5, 6 } } })
  local product = context:batch_matmul(a, b)
  assert_eq(table.concat(product:shape(), ","), "2,2,2")
  assert_eq(product:totable()[1][1][1], 4)
  assert_eq(product:totable()[1][2][2], 11)
  local adjoint = context:batch_matmul(
    context:constant({ { 1, 2 }, { 3, 4 }, { 5, 6 } }),
    context:constant({ { 1, 0 }, { 0, 1 }, { 1, 1 } }), { adj_x = true })
  assert_eq(adjoint:totable()[1][1], 6)
  assert_eq(adjoint:totable()[2][2], 10)
  local filled = context:fill({ 2, 3 }, 7)
  assert_eq(table.concat(filled:shape(), ","), "2,3")
  assert_eq(filled:totable()[2][3], 7)
  local scalar = context:fill({}, 3)
  assert_eq(#scalar:shape(), 0)
  assert_eq(scalar:totable(), 3)
  local sequence = context:range(1, 6, 2, "int32")
  assert_eq(sequence:dtype(), "int32")
  assert_eq(table.concat(sequence:totable(), ","), "1,3,5")
  local spaced = context:linspace(0, 1, 5)
  assert_eq(table.concat(spaced:totable(), ","), "0,0.25,0.5,0.75,1")
  local log_values = context:log_softmax(context:constant({ 0, 1, 2 })):totable()
  assert_true(math.abs(math.exp(log_values[1]) + math.exp(log_values[2]) +
    math.exp(log_values[3]) - 1) < 1e-6)
  assert_error(function()
    context:batch_matmul(a, b, { adj_x = "yes" })
  end, "boolean")
  assert_error(function() context:fill("dims", 1) end, "dims table")
  assert_error(function() context:linspace(0, 1, 0) end, "positive")
  context:close()
end)

